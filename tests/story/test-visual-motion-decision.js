  function keywordProvider(map) {
    return (shot, scene, beatMap) => {
      const beats = (shot.beatIds || []).map((id) => (beatMap && beatMap.beats.find((b) => b.beatId === id))).filter(Boolean);
      const text = beats.map((b) => b.summary || "").join(" ").toLowerCase();
      const sig = { visualType: (map.purpose && map.purpose[shot.shotPurpose]) || "ENVIRONMENT" };
      if (/map|route|migration/.test(text)) sig.visualType = "MAP";
      if (/timeline|chronolog|over the decades|year by year/.test(text)) sig.visualType = "TIMELINE";
      if (/diagram|mechanism|process step|how it works/.test(text)) sig.visualType = "DIAGRAM";
      if (/record|archive|document|ledger/.test(text) && shot.shotPurpose === "EVIDENCE_VISUAL") sig.visualType = "EVIDENCE";
      let actionMatched = false;
      for (const [re, flags] of map.motion) {
        if (new RegExp(re, "i").test(text)) {
          Object.assign(sig, flags);
          if (flags.physicalInteraction) actionMatched = true;
        }
      }
      // Real physical action is character motion, not an explanatory visual.
      if (actionMatched && sig.visualType !== "EVIDENCE") sig.visualType = "CHARACTER_SCENE";
      // Closed world: every unspecified motion signal is explicitly false.
      for (const k of ["subjectMovement", "physicalInteraction", "essentialToUnderstanding", "temporalTransformation", "environmentalDynamics", "revealProgression", "causeEffectOverTime", "cameraMovementNeeded", "turningPoint", "emotionalPayoff"]) {
        if (sig[k] === undefined) sig[k] = false;
      }
      return sig;
    };
  }

